const LangCtx = createContext(null);
export const useLang = () => useContext(LangCtx);

// 翻译函数：中文 key → 英文；查不到返回原文
export function useT() {
  const { lang } = useContext(LangCtx);
  return useCallback(
    (zh) => (lang === "en" ? DICT[zh] ?? zh : zh),
    [lang]
  );
}

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      return localStorage.getItem("pi-lang") || "zh";
    } catch {
      return "zh";
    }
  });

  const setLang = useCallback((l) => {
    setLangState(l);
    try {
      localStorage.setItem("pi-lang", l);
    } catch { /* ignore */ }
  }, []);

  // 应用 lang 属性到根元素（供 CSS 可选使用）
  useEffect(() => {
    document.documentElement.setAttribute("lang", lang);
  }, [lang]);

  const value = useMemo(() => ({ lang, setLang, t: (zh) => (lang === "en" ? DICT[zh] ?? zh : zh) }), [lang, setLang]);

  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}
